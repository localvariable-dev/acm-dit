-- Run this once in Supabase SQL Editor.
-- The public anon key is safe for browser use; RLS should protect the table.

create table if not exists public.acm_applications (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null,
  email text not null,
  phone text not null,
  year text not null,
  branch text not null,
  interests text[] default '{}',
  skills text,
  previous_experience text,
  linkedin text,
  github text
);

alter table public.acm_applications enable row level security;

-- Public applicants can submit applications. They cannot read/update/delete rows.
create policy "allow public application inserts"
on public.acm_applications
for insert
to anon
with check (true);
